// 3. Swap two variables
let a = 10;
let b = 20;

[a, b] = [b, a];

console.log("a:", a); // 20
console.log("b:", b); // 10


// 4. Celsius to Fahrenheit
const celsius = 25;
const fahrenheit = (celsius * 9) / 5 + 32;

console.log("Fahrenheit:", fahrenheit); // 77

// 5. Check whether a number is even or odd
const number = -2;

if (number % 2 === 0) {
  console.log("Even");
} else {
  console.log("Odd");
}
